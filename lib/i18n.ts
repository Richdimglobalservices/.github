export function formatCurrency(amount: number, currency: string = "USD", lang: Language = "en"): string {
  const localeMap: Record<Language, string> = {
    en: "en-US",
    es: "es-ES",
    fr: "fr-FR",
    de: "de-DE",
    zh: "zh-CN",
    ar: "ar-SA",
  };

  return new Intl.NumberFormat(localeMap[lang], {
    style: "currency",
    currency,
  }).format(amount);
}

export function formatDate(date: string | Date, lang: Language = "en"): string {
  const localeMap: Record<Language, string> = {
    en: "en-US",
    es: "es-ES",
    fr: "fr-FR",
    de: "de-DE",
    zh: "zh-CN",
    ar: "ar-SA",
  };

  return new Intl.DateTimeFormat(localeMap[lang], {
    year: "numeric",
    month: "short",
    day: "numeric",
  }).format(new Date(date));
}
